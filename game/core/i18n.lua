M.lang = "en"
M.strings = STRINGS

-- Menu order. `native` is what the in-game language picker shows.
M.languages = { "en", "fr", "it", "de", "es", "tr", "pt", "ru", "pl", "nl" }
M.native = {
	en = "English", ru = "Русский", de = "Deutsch", fr = "Français", es = "Español",
	it = "Italiano", pt = "Português", pl = "Polski", tr = "Türkçe", nl = "Nederlands",
}

local SUPPORTED = {}
for _, code in ipairs(M.languages) do SUPPORTED[code] = true end

-- Poki URL/device language code (e.g. "de", "pt-BR", "en-US") -> supported language.
function M.detect(code)
	local base = tostring(code or ""):lower():gsub("_", "-"):match("^([a-z]+)") or ""
	if base == "uk" or base == "be" or base == "kk" then return "ru" end
	return SUPPORTED[base] and base or "en"
end

-- Accepts Poki / device codes too (e.g. "pt-BR", "de_DE"); unsupported -> English.
function M.set_lang(lang)
	lang = M.detect(lang)
	M.lang = STRINGS[lang] and lang or "en"
end

function M.t(key)
	local s = STRINGS[M.lang][key] or STRINGS.en[key]
	return s or key
end

function M.f(key, ...)
	local ok, s = pcall(string.format, M.t(key), ...)
	return ok and s or M.t(key)
end

-- Pick the current language from a { en = ..., de = ..., ... } table.
function M.pick(t)
	if type(t) ~= "table" then return tostring(t or "") end
	return t[M.lang] or t.en or ""
end

-- 12345 -> "12 345"
function M.money(n)
	local s = tostring(math.floor((n or 0) + 0.5))
	local neg = s:sub(1, 1) == "-"
	if neg then s = s:sub(2) end
	local out = s:reverse():gsub("(%d%d%d)", "%1 "):reverse():gsub("^ ", "")
	return (neg and "-" or "") .. out
end

return M
